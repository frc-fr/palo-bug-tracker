function detectLanguage() {
  const wanted = new URLSearchParams(location.hash.slice(1)).get("lang") || localStorage.getItem("language");
  if (wanted in TEXTS) return wanted;
  return navigator.language.toLowerCase().startsWith("fr") ? "fr" : "en";
}

const language = detectLanguage();
const locale = language === "fr" ? "fr-FR" : "en-GB";

function t(key, values = {}) {
  return TEXTS[language][key].replace(/\{(\w+)\}/g, (_, name) => values[name]);
}

document.documentElement.lang = language;
for (const element of document.querySelectorAll("[data-text]")) element.textContent = t(element.dataset.text);
for (const element of document.querySelectorAll("[data-html]")) element.innerHTML = t(element.dataset.html);
for (const element of document.querySelectorAll("[data-placeholder]")) element.placeholder = t(element.dataset.placeholder);
for (const element of document.querySelectorAll("[data-label]")) element.setAttribute("aria-label", t(element.dataset.label));
